package server

import "testing"

func TestScheduleAnchorsAndBoundaries(t *testing.T) {
	for _, c := range []struct {
		start, repeat    string
		interval         int
		on, latest, next string
	}{
		{"2026-01-01", "daily", 3, "2026-01-11", "2026-01-10", "2026-01-13"},
		{"2026-01-01", "once", 1, "2025-12-31", "", "2026-01-01"},
		{"2026-01-01", "once", 1, "2026-03-01", "2026-01-01", ""},
		{"2026-01-01", "weekly", 2, "2026-01-15", "2026-01-15", "2026-01-29"},
		{"2025-01-31", "monthly", 1, "2025-03-01", "2025-02-28", "2025-03-31"},
		{"2025-01-31", "monthly", 2, "2025-04-01", "2025-03-31", "2025-05-31"},
		{"2024-02-29", "yearly", 1, "2027-03-01", "2027-02-28", "2028-02-29"},
		{"2024-02-29", "yearly", 4, "2028-02-28", "2024-02-29", "2028-02-29"},
		{"0001-01-01", "daily", 1, "9999-12-31", "9999-12-31", ""},
		{"0001-01-01", "weekly", 1, "9999-12-31", "9999-12-27", ""},
		{"0001-01-31", "monthly", 1, "9999-12-31", "9999-12-31", ""},
		{"0001-01-01", "yearly", 365, "9999-12-31", "9856-01-01", ""},
	} {
		s, _ := isoDate(c.start, "date")
		on, _ := isoDate(c.on, "date")
		a, b := around(s, c.repeat, c.interval, on)
		as, bs := "", ""
		if a.Year() != 0 {
			as = a.Format("2006-01-02")
		}
		if b.Year() != 0 {
			bs = b.Format("2006-01-02")
		}
		if as != c.latest || bs != c.next {
			t.Errorf("%+v got %s %s", c, as, bs)
		}
	}
}
